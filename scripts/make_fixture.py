"""Build tests/fixtures/01_fixture.sql.gz: the 14 registered tables (same names, columns and types) with a small
recorded extract of real rows, for API tests against a local Postgres. Read-only against Supabase; no secrets are
written (only table data).

Extract: districts Alfred Nzo, City of Cape Town (alias 'cape town' in Module 1 satellite/hydrology tables) and
Namakwa; daily tables from 2024-01-01, monthly/annual tables complete.

Usage: python scripts/make_fixture.py
"""

from __future__ import annotations

import datetime as dt
import decimal
import gzip
import sys
from pathlib import Path

import psycopg
from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.registry.registry import load_registry  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "01_fixture.sql.gz"
DISTRICTS = ["Alfred Nzo", "City of Cape Town", "Namakwa"]
ALIASES = ["alfred nzo", "cape town", "namakwa"]
DAILY_FROM = "2024-01-01"


def lit(v: object) -> str:
    if v is None:
        return "\\N"
    if isinstance(v, bool):
        return "t" if v else "f"
    if isinstance(v, dt.date | dt.datetime):
        return v.isoformat()
    if isinstance(v, float | decimal.Decimal):
        return repr(float(v))
    s = str(v)
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def main() -> None:
    url = dotenv_values(ROOT / ".env")["SUPABASE_DB_URL"]
    reg = load_registry()
    out: list[str] = [
        "-- Generated by scripts/make_fixture.py — recorded extract of the NIWIS tables for tests.\n",
        "SET client_encoding = 'UTF8';\n",
    ]
    with psycopg.connect(url, autocommit=True) as c:
        c.execute("SET SESSION CHARACTERISTICS AS TRANSACTION READ ONLY")
        for ds in reg.datasets.values():
            cols = c.execute(
                "SELECT column_name, format_type(a.atttypid, a.atttypmod) AS t, NOT a.attnotnull AS nullable "
                "FROM information_schema.columns ic JOIN pg_attribute a ON a.attrelid = to_regclass(%s) "
                "AND a.attname = ic.column_name WHERE ic.table_schema = %s AND ic.table_name = %s "
                "ORDER BY ic.ordinal_position",
                (f'"{ds.schema_}"."{ds.table}"', ds.schema_, ds.table),
            ).fetchall()
            names = [f'"{n}"' for n, _, _ in cols]
            ddl = ",\n  ".join(f'"{n}" {t}{"" if nullable else " NOT NULL"}' for n, t, nullable in cols)
            out.append(f'\nCREATE TABLE "{ds.table}" (\n  {ddl}\n);\n')
            loc = f'"{ds.location.column}"'
            where = f"lower({loc}) = ANY(%s)"
            params: list[object] = [[n.lower() for n in DISTRICTS + ALIASES]]
            if ds.time.resolution == "daily":
                where += f" AND {ds.date_sql()} >= %s::date"
                params.append(DAILY_FROM)
            rows = c.execute(f"SELECT {', '.join(names)} FROM {ds.fq} WHERE {where} ORDER BY 1, 2", params).fetchall()
            out.append(f'COPY "{ds.table}" ({", ".join(names)}) FROM stdin;\n')
            out.extend("\t".join(lit(v) for v in r) + "\n" for r in rows)
            out.append("\\.\n")
            print(f"{ds.table}: {len(rows)} rows")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(OUT, "wt", encoding="utf-8", newline="\n") as fh:
        fh.writelines(out)
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()

"""Generate the database view's catalogue from the database schema (read-only).

Reads `information_schema.columns` (schema `public`), applies app/registry/datasets.yaml (roles, reasons, resolution)
and app/core/units.py (labels, units), and writes:
- app/registry/catalogue.yaml — loaded by the API (`/api/v1/{module}/categories`, `/category/{tableId}/{groupId}`);
- docs/CATEGORY_CATALOGUE.md — every table, every column, its label, unit, chart group and status (for DWS and the
  data team).

New columns in registered tables appear automatically (withheld until reviewed); new tables are listed as unregistered
until they are added to the registry. Nothing else needs to change in code.

Usage:
    python scripts/build_catalogue.py            # regenerate both files from Supabase (SUPABASE_DB_URL in .env)
    python scripts/build_catalogue.py --check    # exit 1 if the committed files are out of date
    python scripts/build_catalogue.py --db-url postgresql://…   # another database (e.g. the test fixture)
Never prints secrets.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from collections import Counter
from pathlib import Path

import psycopg
from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.core.units import LABEL_OVERRIDES, SUFFIXES  # noqa: E402
from app.registry.catalogue import (  # noqa: E402
    CATALOGUE_PATH,
    Catalogue,
    SchemaColumn,
    build_catalogue,
    dump_yaml,
    load_catalogue,
)
from app.registry.registry import load_registry  # noqa: E402

DOC = ROOT / "docs" / "CATEGORY_CATALOGUE.md"
SCHEMA_SQL = """
SELECT table_name, column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public'
ORDER BY table_name, ordinal_position
"""


def read_schema(url: str) -> dict[str, list[SchemaColumn]]:
    out: dict[str, list[SchemaColumn]] = {}
    with psycopg.connect(url, autocommit=True, connect_timeout=15) as conn:
        conn.execute("SET SESSION CHARACTERISTICS AS TRANSACTION READ ONLY")
        for table, column, dtype in conn.execute(SCHEMA_SQL).fetchall():
            out.setdefault(str(table), []).append(SchemaColumn(column=str(column), db_type=str(dtype)))
    return out


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def render_markdown(cat: Catalogue) -> str:
    lines = [
        "# Database category catalogue",
        "",
        f"> Generated by `python scripts/build_catalogue.py` from the database schema on {cat.generated} — do not edit.",
        "> Every registered table is a **category**, every column a **variable**. Labels and units come from the column",
        "> names; nothing is renamed. Served by `GET /api/v1/{module}/categories` and",
        "> `GET /api/v1/{module}/category/{tableId}/{groupId}` (docs/FRONTEND_INTEGRATION.md, “Database category charts”).",
        "",
        "## How to read this",
        "",
        "- **Label and unit** from the column name: the unit is the name's suffix (`_mm_day` → mm/day, `_C` → °C,",
        "  `_pct` → %, …; table below), the label is the rest with underscores as spaces, words capitalised and acronyms",
        "  as written (`ET0` → ET₀). Names without a unit suffix have no unit, except the few overrides listed below.",
        "- **Status**: `live` = served; `withheld` = not served, with the reason (placeholders, failed plausibility",
        "  checks, docs/DATA_GAPS.md); `duplicate` = identical to another column (named), listed but not charted so the",
        "  same number never appears twice under two names. Key columns (district, date, year, month, day, id) are not",
        "  variables.",
        "- **Chart group**: columns that are drawn together. A group never mixes units (one axis); unitless standardised",
        "  indices (SPI, SPEI, SSI, SGI, RAI, SVI) share an index axis, spectral indices (NDVI, NDWI, …) another. Columns",
        "  marked ★ are shown by default; every other column of the group can be switched on.",
        "- **Resolution**: daily, monthly or annual. Monthly / annual values that the database repeats on every daily row",
        "  are read once per period. Incomplete months / years (e.g. 2026) are never served.",
        "",
        "## Summary",
        "",
        "| Category (table) | Spec | Pages | Live | Withheld | Duplicate | Chart groups |",
        "| --- | --- | --- | ---: | ---: | ---: | --- |",
    ]
    for c in cat.categories:
        n = Counter(x.status for x in c.columns)
        lines.append(
            f"| [{c.label}](#{c.id}) (`{c.table}`) | §{c.spec or '—'} | {', '.join(c.modules)} | {n['live']} | "
            f"{n['withheld']} | {n['duplicate']} | {len(c.groups)} |"
        )
    tot = Counter(x.status for c in cat.categories for x in c.columns)
    lines += [
        f"| **Total** | | | **{tot['live']}** | **{tot['withheld']}** | **{tot['duplicate']}** | "
        f"**{sum(len(c.groups) for c in cat.categories)}** |",
        "",
    ]
    for c in cat.categories:
        n = Counter(x.status for x in c.columns)
        lines += [
            f'<a id="{c.id}"></a>',
            f"## {c.label} · §{c.spec or '—'}",
            "",
            f"Table `{c.table}` · id `{c.id}` · {c.resolution} · pages: {', '.join(c.modules)} · "
            f"{n['live']} live, {n['withheld']} withheld, {n['duplicate']} duplicate · keys: "
            + ", ".join(f"`{k}`" for k in c.keys),
            "",
            "| Chart group | id | Axis unit | Resolution | Columns (★ default) |",
            "| --- | --- | --- | --- | --- |",
        ]
        for g in c.groups:
            cols = ", ".join(f"`{x}`" + (" ★" if x in g.default_visible else "") for x in g.columns)
            lines.append(f"| {g.label} | `{g.id}` | {g.unit} | {g.resolution} | {cols} |")
        lines += [
            "",
            "| Column | Label | Unit | Resolution | Group | Status |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for x in c.columns:
            if x.status == "withheld":
                status = f"withheld — {_cell(x.reason)}"
            elif x.status == "duplicate":
                status = f"duplicate of `{x.duplicate_of}`"
            else:
                status = "live" + (f" — {_cell(x.note)}" if x.note else "")
            unit = (x.unit or "—") + (" ¹" if x.unit_override else "")
            kind = " (class)" if x.kind == "categorical" else ""
            lines.append(
                f"| `{x.column}` | {_cell(x.label)}{kind} | {unit} | {x.resolution} | "
                f"{('`' + x.group + '`') if x.group else '—'} | {status} |"
            )
        lines.append("")
    lines += [
        "## Unit suffixes (app/core/units.py)",
        "",
        "| Suffix | Unit |",
        "| --- | --- |",
        *[f"| `{s}` | {u or 'none (dimensionless)'} |" for s, u in SUFFIXES],
        "",
        "## Unit overrides (¹)",
        "",
        "Only where the name carries no unit or the wrong one; never to rename a variable.",
        "",
        "| Table | Column | Unit | Why |",
        "| --- | --- | --- | --- |",
        *[f"| `{t}` | `{col}` | {o.unit} | {_cell(o.why)} |" for (t, col), o in LABEL_OVERRIDES.items()],
        "",
        "## Tables in the database that are not registered",
        "",
    ]
    if not cat.unregistered:
        lines.append("None.")
    else:
        lines += [
            "Present in the database but not served yet: each needs a module page, its key and time columns registered in",
            "`app/registry/datasets.yaml`, and a plausibility check (docs/DATA_GAPS.md §16). Their columns:",
            "",
            "| Table | Columns |",
            "| --- | --- |",
        ]
        for u in cat.unregistered:
            lines.append(f"| `{u.table}` | {', '.join(f'`{_cell(x.column)}`' for x in u.columns)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed files are out of date")
    ap.add_argument("--db-url", help="database URL (default: SUPABASE_DB_URL from .env)")
    args = ap.parse_args()
    url = args.db_url or dotenv_values(ROOT / ".env").get("SUPABASE_DB_URL")
    if not url:
        print("SUPABASE_DB_URL is not set (.env) and --db-url was not given", file=sys.stderr)
        return 2
    schema = read_schema(url)
    today = dt.date.today().isoformat()
    cat = build_catalogue(load_registry(), schema, today)
    if args.check:
        current = load_catalogue()
        if current.model_copy(update={"generated": today}) != cat:
            print("app/registry/catalogue.yaml is out of date: run python scripts/build_catalogue.py", file=sys.stderr)
            return 1
        print("catalogue up to date")
        return 0
    CATALOGUE_PATH.write_text(dump_yaml(cat), encoding="utf-8")
    DOC.write_text(render_markdown(cat), encoding="utf-8")
    n = Counter(x.status for c in cat.categories for x in c.columns)
    print(
        f"wrote {CATALOGUE_PATH.relative_to(ROOT)} and {DOC.relative_to(ROOT)}: {len(cat.categories)} categories, "
        f"{sum(len(c.groups) for c in cat.categories)} chart groups, {dict(n)}, {len(cat.unregistered)} unregistered"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
